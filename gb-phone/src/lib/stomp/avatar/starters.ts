export function configFromStarter(
  s: StarterDef,
  opts: { stomperId: string; displayName?: string; stylePath?: StylePath } = {
    stomperId: "local",
  },
): AvatarConfig {
  const now = new Date().toISOString();
  return {
    version: 1,
    stomperId: opts.stomperId,
    starterId: s.id,
    // Starter `.label` is an appearance-template tag only — never a silent displayName.
    displayName: opts.displayName ?? "",
    presenting: s.presenting,
    ageBand: s.ageBand,
    stylePath: opts.stylePath ?? s.styleHint,
    layers: layersFromStarter(s),
    poseId: "idle",
    backgroundId: s.styleHint === "park-street" ? "bg-park" : "bg-powder",
    stage: 1,
    personalize: { ...EMPTY_PERSONALIZE },
    createdAtIso: now,
    updatedAtIso: now,
  };
}
